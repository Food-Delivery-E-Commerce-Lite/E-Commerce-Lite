CREATE TABLE users (
    user_id       BIGSERIAL PRIMARY KEY,
    email         VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(100) NOT NULL,
    phone         VARCHAR(20),
    role          VARCHAR(20) NOT NULL CHECK (role IN ('CUSTOMER','MERCHANT','ADMIN')),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE addresses (
    address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    label      VARCHAR(50),
    street     VARCHAR(200) NOT NULL,
    district   VARCHAR(100),
    city       VARCHAR(100),
    lat        DECIMAL(9,6),
    lng        DECIMAL(9,6),
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_addresses_user ON addresses(user_id);

CREATE TABLE restaurants (
    restaurant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    name          VARCHAR(150) NOT NULL,
    description   TEXT,
    address       VARCHAR(250),
    lat           DECIMAL(9,6),
    lng           DECIMAL(9,6),
    open_time     TIME,
    close_time    TIME,
    status        VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                  CHECK (status IN ('PENDING','APPROVED','REJECTED','LOCKED')),
    avg_rating    DECIMAL(3,2) NOT NULL DEFAULT 0,
    rating_count  INT NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version       BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_restaurants_status_name ON restaurants(status, name);
CREATE INDEX idx_restaurants_owner ON restaurants(owner_id);

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE menu_items (
    item_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(restaurant_id) ON DELETE CASCADE,
    category_id   BIGINT REFERENCES categories(category_id) ON DELETE SET NULL,
    name          VARCHAR(150) NOT NULL,
    description   TEXT,
    price         DECIMAL(12,0) NOT NULL CHECK (price > 0),
    image_url     VARCHAR(300),
    is_available  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_menu_items_restaurant ON menu_items(restaurant_id, name);
CREATE INDEX idx_menu_items_restaurant_avail ON menu_items(restaurant_id, is_available);

CREATE TABLE orders (
    order_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id   BIGINT NOT NULL REFERENCES users(user_id),
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(restaurant_id),
    address_id    BIGINT NOT NULL REFERENCES addresses(address_id),
    status        VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                  CHECK (status IN ('PENDING','CONFIRMED','PREPARING','DELIVERING','COMPLETED','CANCELLED')),
    subtotal      DECIMAL(12,0) NOT NULL CHECK (subtotal >= 0),
    delivery_fee  DECIMAL(12,0) NOT NULL CHECK (delivery_fee >= 0),
    total_amount  DECIMAL(12,0) NOT NULL CHECK (total_amount >= 0),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version       BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_orders_customer ON orders(customer_id, created_at DESC);
CREATE INDEX idx_orders_restaurant_status ON orders(restaurant_id, status);
CREATE INDEX idx_orders_created_at ON orders(created_at);

CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    item_id       BIGINT NOT NULL REFERENCES menu_items(item_id),
    item_name     VARCHAR(150) NOT NULL,
    unit_price    DECIMAL(12,0) NOT NULL CHECK (unit_price >= 0),
    quantity      INT NOT NULL CHECK (quantity BETWEEN 1 AND 50)
);
CREATE INDEX idx_order_items_order ON order_items(order_id);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT NOT NULL UNIQUE REFERENCES orders(order_id) ON DELETE CASCADE,
    method     VARCHAR(20) NOT NULL CHECK (method IN ('COD','ONLINE')),
    status     VARCHAR(20) NOT NULL DEFAULT 'PENDING'
               CHECK (status IN ('PENDING','PAID','FAILED','REFUNDED')),
    paid_at    TIMESTAMPTZ
);

CREATE TABLE reviews (
    review_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      BIGINT NOT NULL UNIQUE REFERENCES orders(order_id) ON DELETE CASCADE,
    user_id       BIGINT NOT NULL REFERENCES users(user_id),
    restaurant_id BIGINT NOT NULL REFERENCES restaurants(restaurant_id) ON DELETE CASCADE,
    rating        INT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment       TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_review_user_restaurant_order UNIQUE (user_id, restaurant_id, order_id)
);
CREATE INDEX idx_reviews_restaurant ON reviews(restaurant_id, created_at DESC);

CREATE TABLE order_status_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL REFERENCES orders(order_id) ON DELETE CASCADE,
    from_status VARCHAR(20),
    to_status   VARCHAR(20) NOT NULL,
    changed_by  BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    changed_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_history_order ON order_status_history(order_id, changed_at);

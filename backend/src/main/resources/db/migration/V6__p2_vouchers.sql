-- P2-3: voucher & giảm giá + hoàn tiền
CREATE TABLE IF NOT EXISTS vouchers (
    voucher_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    type VARCHAR(20) NOT NULL CHECK (type IN ('PERCENT','FIXED','FREESHIP')),
    value DECIMAL(12,0) NOT NULL DEFAULT 0 CHECK (value >= 0),
    min_order DECIMAL(12,0) NOT NULL DEFAULT 0 CHECK (min_order >= 0),
    max_discount DECIMAL(12,0),
    usage_limit INT,
    used_count INT NOT NULL DEFAULT 0,
    restaurant_id BIGINT REFERENCES restaurants(restaurant_id) ON DELETE CASCADE,
    valid_from TIMESTAMPTZ,
    valid_to TIMESTAMPTZ,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_vouchers_code ON vouchers(code);
CREATE INDEX IF NOT EXISTS idx_vouchers_restaurant ON vouchers(restaurant_id);

ALTER TABLE orders ADD COLUMN IF NOT EXISTS discount_amount DECIMAL(12,0) NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN IF NOT EXISTS voucher_code VARCHAR(50);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS voucher_id BIGINT REFERENCES vouchers(voucher_id) ON DELETE SET NULL;

